static string Cap(string value) { return char.ToUpperInvariant(value[0]) + value.Substring(1); }
static Noun N(string value, bool suffix) {
    Noun result;
    if ((suffix ? SuffixOverrides : MiddleOverrides).TryGetValue(value, out result)) return result;
    if (Nouns.TryGetValue(value, out result)) return result;
    throw new InvalidOperationException("Unreviewed worksite name noun: " + value);
}
static string Part(string value) {
    string result;
    return Proper.TryGetValue(value, out result) ? result : N(value, false).Text;
}
static string Describe(string prefix, Noun noun) {
    string particle;
    if (Particles.TryGetValue(prefix, out particle)) return particle + (char.IsUpper(noun.Text[0]) ? "-" : "") + noun.Text;
    string[] forms;
    if (!Adjectives.TryGetValue(prefix, out forms)) throw new InvalidOperationException("Unreviewed worksite name adjective: " + prefix);
    int index = "mfnp".IndexOf(noun.Gender, StringComparison.Ordinal);
    return forms[index] + " " + noun.Text;
}
static string Three(string prefix, string middle, string suffix) {
    Noun kind = N(suffix, true);
    string place;
    if (ProperPrefixes.TryGetValue(prefix, out place))
        return Cap(kind.Text) + " «" + Cap(N(middle,false).Text) + " " + ProperPrefixGenitives[prefix] + "»";
    string proper;
    if (Proper.TryGetValue(middle, out proper))
        return Cap(Describe(prefix,kind)) + " «" + proper + "»";
    return Cap(kind.Text) + " «" + Cap(Describe(prefix,N(middle,false))) + "»";
}
public static string FromArray(string[] parts) {
    if (parts.Length != 5) throw new InvalidOperationException("Unexpected worksite name array layout");
    string suffix = N(parts[4],true).Text;
    if (parts[1] == " & ")
        return Cap(suffix) + " «" + Cap(Part(parts[0])) + " и " + Part(parts[2]) + "»";
    if (parts[1] == "-")
        return Cap(suffix) + " «" + Proper[parts[0]] + " — " + Proper[parts[2]] + "»";
    if (parts[1] != " " || parts[3] != " ") throw new InvalidOperationException("Unexpected worksite name separators");
    return Three(parts[0],parts[2],parts[4]);
}
public static string FromFour(string first,string second,string third,string fourth) {
    if (third != " ") throw new InvalidOperationException("Unexpected worksite name separator");
    if (first != "The ") return Three(first,second,fourth);
    Noun kind = N(fourth,true);
    string place;
    if (ProperPrefixes.TryGetValue(second,out place)) return Cap(kind.Text) + " «" + place + "»";
    return Cap(Describe(second,kind));
}
